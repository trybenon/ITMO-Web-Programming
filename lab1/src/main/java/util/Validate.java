package util;

public class Validate {
    public static boolean validateX(double x) {
        return x >= -3 && x <= 5;
    }

    public static boolean validateY(double y) {
        return y >= -3 && y <= 3;
    }

    public static boolean validateR(double r) {
        return r >= 1 && r <= 3;
    }

}
